import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface EnvVariable {
  name: string;
  description: string;
  required: boolean;
  default?: string;
  example?: string;
}

const REQUIRED_ENV_VARS: EnvVariable[] = [
  {
    name: "VERDACCIO_URL_DOCKER",
    description: "Docker-internal URL for npm registry",
    required: true,
    default: "http://verdaccio:4873",
    example: "http://verdaccio:4873",
  },
  {
    name: "VERDACCIO_URL",
    description: "Local development URL for npm registry",
    required: false,
    default: "http://localhost:4873",
  },
  {
    name: "TILT_ENV",
    description: "Tilt environment name",
    required: true,
    default: "dev",
    example: "dev",
  },
  {
    name: "DATABASE_URL",
    description: "PostgreSQL connection string",
    required: false,
    default: "postgresql://postgres:postgres@postgres:5432/app_dev",
  },
  {
    name: "DB_PASSWORD",
    description: "PostgreSQL superuser password (docker-compose POSTGRES_PASSWORD)",
    required: true,
    default: "postgres",
    example: "postgres",
  },
];

export function generateEnvFile(projectRoot: string): string {
  const lines: string[] = [
    "# 🔧 TDK Environment Configuration",
    "# Auto-generated by TDK CLI - edit as needed",
    "# These variables are required for services to run",
    "#",
    "# After editing, run: tdk config regenerate && tdk up",
    "",
  ];

  for (const envVar of REQUIRED_ENV_VARS) {
    lines.push(`# ${envVar.description}`);

    if (envVar.required) {
      lines.push(`# ⚠️  REQUIRED - set this or services will fail`);
    }

    if (envVar.example) {
      lines.push(`# Example: ${envVar.example}`);
    }

    lines.push(`${envVar.name}=${envVar.default || ""}`);
    lines.push("");
  }

  return lines.join("\n");
}

export function validateEnvFile(projectRoot: string): {
  missing: string[];
  invalid: string[];
  warnings: string[];
} {
  const envPath = join(projectRoot, ".env");
  const result = {
    missing: [] as string[],
    invalid: [] as string[],
    warnings: [] as string[],
  };

  if (!existsSync(envPath)) {
    return {
      missing: REQUIRED_ENV_VARS.filter((v) => v.required).map((v) => v.name),
      invalid: [],
      warnings: [".env file not found - will be auto-generated"],
    };
  }

  const envContent = readFileSync(envPath, "utf-8");
  const envVars = new Set(
    envContent
      .split("\n")
      .filter((line) => !line.startsWith("#") && line.includes("="))
      .map((line) => line.split("=")[0])
      .filter((name) => name.length > 0)
  );

  for (const envVar of REQUIRED_ENV_VARS) {
    if (envVar.required && !envVars.has(envVar.name)) {
      result.missing.push(envVar.name);
    }

    if (envVars.has(envVar.name)) {
      const match = envContent.match(new RegExp(`^${envVar.name}=(.*)$`, "m"));
      const value = match ? match[1] : "";
      if (!value.trim()) {
        result.invalid.push(`${envVar.name} is set but empty`);
      }
    }
  }

  return result;
}

export function ensureEnvFile(projectRoot: string): boolean {
  const envPath = join(projectRoot, ".env");

  if (!existsSync(envPath)) {
    writeFileSync(envPath, generateEnvFile(projectRoot));
    return true;
  }

  return false;
}
