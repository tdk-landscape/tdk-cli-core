describe("SKIP_DIRECTORIES", () => {
  it("should skip node_modules", () => {
    expect(includes(SKIP_DIRECTORIES, "node_modules")).toBe(true);
  });

  it("should skip .git", () => {
    expect(includes(SKIP_DIRECTORIES, ".git")).toBe(true);
  });

  it("should skip dist", () => {
    expect(includes(SKIP_DIRECTORIES, "dist")).toBe(true);
  });

  it("should NOT skip regular project directories", () => {
    expect(includes(SKIP_DIRECTORIES, "services")).toBe(false);
    expect(includes(SKIP_DIRECTORIES, "shared")).toBe(false);
    expect(includes(SKIP_DIRECTORIES, "backend")).toBe(false);
    expect(includes(SKIP_DIRECTORIES, "frontend")).toBe(false);
  });

  it("should skip coverage", () => {
    expect(includes(SKIP_DIRECTORIES, "coverage")).toBe(true);
  });

  it("should skip test directories", () => {
    expect(includes(SKIP_DIRECTORIES, "__tests__")).toBe(true);
    expect(includes(SKIP_DIRECTORIES, "test")).toBe(true);
    expect(includes(SKIP_DIRECTORIES, "tests")).toBe(true);
  });

  it("should have consistent skip list", () => {
    // These directories should always be skipped
    const mandatorySkips = ["node_modules", ".git", "dist", "build", "coverage"];
    for (const dir of mandatorySkips) {
      expect(includes(SKIP_DIRECTORIES, dir)).toBe(true);
    }
  });
});

