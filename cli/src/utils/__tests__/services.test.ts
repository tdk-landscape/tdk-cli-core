describe("includes type guard", () => {
  it("should return true for values in readonly array", () => {
    const arr = ["a", "b", "c"] as const;
    expect(includes(arr, "a")).toBe(true);
    expect(includes(arr, "b")).toBe(true);
    expect(includes(arr, "c")).toBe(true);
  });

  it("should return false for values not in readonly array", () => {
    const arr = ["a", "b", "c"] as const;
    expect(includes(arr, "d")).toBe(false);
    expect(includes(arr, "")).toBe(false);
  });

  it("should narrow type correctly", () => {
    const arr = ["node_modules", ".git", "dist"] as const;
    const value: string = "node_modules";
    if (includes(arr, value)) {
      expect(value).toBe("node_modules");
    }
  });
});

