/**
 * Type guard to validate if an unknown value is a valid ProjectConfig.
 *
 * NOTE: The `as` assertions below are INTENTIONAL and SAFE:
 * - We've already verified `typeof value === 'object'` and `value !== null`
 * - TypeScript doesn't automatically narrow `{}` to `Record<string, unknown>`
 * - Each assertion is immediately followed by property type checks
 * - This pattern is standard for deep object validation in type guards
 */
function hasPhaseShape(value: unknown, fieldName: "enabledStacks" | "services"): boolean {
  if (!value || typeof value !== "object") return false;
  const phases = value as Record<string, unknown>;
  for (const phaseName of ["pre_alpha", "alpha", "beta", "out_of_scope"]) {
    const phase = phases[phaseName];
    if (!phase || typeof phase !== "object") return false;
    if (!Array.isArray((phase as Record<string, unknown>)[fieldName])) return false;
  }
  return true;
}

function normalizeProjectConfig(value: unknown): ProjectConfig | null {
  if (!value || typeof value !== "object") {
    return null;
  }

  // Safe to assert as Record after null and object type checks
  const config = value as Record<string, unknown>;

  if (typeof config.version !== "string") {
    return null;
  }

  if (!config.project || typeof config.project !== "object") {
    return null;
  }
  const project = config.project as Record<string, unknown>;
  if (typeof project.name !== "string" || typeof project.version !== "string") {
    return null;
  }

  let phases: ProjectConfig["phases"] | null = null;
  if (hasPhaseShape(config.phases, "enabledStacks")) {
    phases = config.phases as ProjectConfig["phases"];
  } else if (hasPhaseShape(config.stacks, "services")) {
    const legacyStacks = config.stacks as NonNullable<ProjectConfig["stacks"]>;
    phases = {
      pre_alpha: {
        name: legacyStacks.pre_alpha.name,
        description: legacyStacks.pre_alpha.description,
        enabledStacks: legacyStacks.pre_alpha.services,
      },
      alpha: {
        name: legacyStacks.alpha.name,
        description: legacyStacks.alpha.description,
        enabledStacks: legacyStacks.alpha.services,
      },
      beta: {
        name: legacyStacks.beta.name,
        description: legacyStacks.beta.description,
        enabledStacks: legacyStacks.beta.services,
      },
      out_of_scope: {
        name: legacyStacks.out_of_scope.name,
        description: legacyStacks.out_of_scope.description,
        enabledStacks: legacyStacks.out_of_scope.services,
      },
    };
  }

  if (!phases) {
    return null;
  }

  if (!config.optional_infra || typeof config.optional_infra !== "object") {
    return null;
  }
  const optionalInfra = config.optional_infra as Record<string, unknown>;
  if (
    typeof optionalInfra.monitoring !== "boolean" ||
    typeof optionalInfra.elk !== "boolean" ||
    typeof optionalInfra.debezium !== "boolean" ||
    typeof optionalInfra.golden_image !== "boolean" ||
    typeof optionalInfra.verdaccio !== "boolean"
  ) {
    return null;
  }

  if (!config.discovery || typeof config.discovery !== "object") {
    return null;
  }
  const discovery = config.discovery as Record<string, unknown>;
  if (!Array.isArray(discovery.paths)) {
    return null;
  }

  return {
    version: config.version,
    project: config.project as ProjectConfig["project"],
    phases,
    always_enabled_infra: config.always_enabled_infra as string[] | undefined,
    optional_infra: config.optional_infra as ProjectConfig["optional_infra"],
    discovery: config.discovery as ProjectConfig["discovery"],
    overrides: config.overrides as ProjectConfig["overrides"],
  };
}

export function readProjectConfig(projectRoot: string): ProjectConfig {
  const projectJsonPath = path.join(projectRoot, ".tdk", "project.json");

  if (!fs.existsSync(projectJsonPath)) {
    throw new Error(`Project config not found: ${projectJsonPath}. Run 'tdk project init' first.`);
  }

  const jsonContent = fs.readFileSync(projectJsonPath, "utf-8");
  const parsed: unknown = JSON.parse(jsonContent);

  const projectConfig = normalizeProjectConfig(parsed);
  if (!projectConfig) {
    throw new Error(
      "Invalid project.json: missing or invalid required fields. " +
        "Expected: version (string), project (object with name/version), " +
        "phases (object with pre_alpha/alpha/beta/out_of_scope enabledStacks), " +
        "optional_infra (object with boolean flags), " +
        "discovery (object with paths array)",
    );
  }

  return projectConfig;
}

export async function generateMasterConfigs(projectRoot: string): Promise<void> {
  const projectConfig = readProjectConfig(projectRoot);

  // Verdaccio is Premium - this is the one choke point every path funnels
  // through (project init, config regenerate, and the wizard all call this
  // before `tdk up` reads .tdk-out), so it's the real enforcement, not just
  // the CLI's `config enable-infra` guard. A hand-edited project.json with
  // optional_infra.verdaccio: true can't skip the check; it just gets
  // silently downgraded back to false with a warning.
  if (projectConfig.optional_infra.verdaccio) {
    const granted = await hasVerdaccioLicense(projectRoot);
    if (!granted) {
      console.warn(
        "⚠️  Verdaccio is a Premium feature - no valid license key found. " +
          "Disabling it for this generation. Set TDK_LICENSE_KEY to a key that grants it, " +
          "or run `tdk config disable-infra verdaccio` to silence this warning.",
      );
      projectConfig.optional_infra.verdaccio = false;
    }
  }

  const outputDir = path.join(projectRoot, ".tdk", ".tdk-out");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const engine = new TemplateEngine();
  const files = engine.generateAll(projectConfig);

  for (const filename of ALL_GENERATED_FILES) {
    const content = files[filename];
    const filePath = path.join(outputDir, filename);
    writeTextFile(filePath, content);
    console.log(`✓ Generated: .tdk/.tdk-out/${filename}`);
  }

  if (isStackFeatureEnabledInStacks(projectConfig.phases, "database-management")) {
    const composeDir = path.join(projectRoot, "services", "platform", "database-management");
    fs.mkdirSync(composeDir, { recursive: true });
    const composePath = path.join(
      composeDir,
      "docker-compose.yml",
    );
    writeTextFile(composePath, generateDatabaseManagementCompose(projectConfig));
    console.log("✓ Generated: services/platform/database-management/docker-compose.yml");
  }

  // Copy .tiltignore to project root so Tilt uses it
  const tiltignoreSource = path.join(outputDir, ".tiltignore");
  const tiltignoreTarget = path.join(projectRoot, ".tiltignore");
  if (fs.existsSync(tiltignoreSource)) {
    fs.copyFileSync(tiltignoreSource, tiltignoreTarget);
    console.log(`✓ Copied: .tiltignore → project root`);
  }

  await vendorTdkExtension(projectRoot);

  console.log("");
  console.log("💡 To start Tilt: tdk up");
}

// The generated Tiltfile loads the TDK Tilt extension (engine, discovery,
// specs, ext starlark modules). The extension repo may stay private, so we
// vendor a working copy into .tdk/.tdk-out/tdk-cli-ext/ at generation time.
// This makes `tdk up` work offline and on any machine - no hardcoded paths,
// no dependency on a private GitHub repo.
const TDK_EXTENSION_DIRS = ["engine", "discovery", "specs", "ext"] as string[];

// Walk up from this module's own location looking for a directory that has
// both Tiltfile and engine/ next to it - true when cli/ and engine/ ship
// together in the same repo (the public tdk-cli-core layout, where a plain
// `git clone` + `bun run` needs zero extra config to find the engine).
function findSelfContainedEngineRoot(): string | null {
  let dir = import.meta.dirname || process.cwd();
  for (let i = 0; i < 6; i++) {
    if (fs.existsSync(path.join(dir, "Tiltfile")) && fs.existsSync(path.join(dir, "engine"))) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

async function vendorTdkExtension(projectRoot: string): Promise<void> {
  const outputDir = path.join(projectRoot, ".tdk", ".tdk-out");
  const vendoredDir = path.join(outputDir, "tdk-cli-ext");

  // Source resolution order:
  //   1. $TDK_EXTENSION_SOURCE (explicit override)
  //   2. Self-contained repo (engine/ ships next to cli/ - public tdk-cli-core)
  //   3. Executable-adjacent checkout (bundled installs)
  //   4. Relative ../tdk-cli sibling (monorepo maintainer layout)
  let sources: string[] = [];
  if (process.env.TDK_EXTENSION_SOURCE) {
    sources.push(process.env.TDK_EXTENSION_SOURCE);
  }
  const selfContainedRoot = findSelfContainedEngineRoot();
  if (selfContainedRoot) {
    sources.push(selfContainedRoot);
  }
  // process.execPath is the compiled binary's own path when running as a
  // standalone executable (what we actually need here). In dev mode it's
  // the bun CLI's own path instead (e.g. ~/.bun/bin/bun) - harmless, that
  // candidate just won't match anything and falls through to the next
  // one. Note: process.executablePath is not a real property on Node or
  // Bun's process object - it was always undefined, silently falling
  // back to cwd() instead of the binary's real location.
  const exeDir = path.dirname(process.execPath);
  sources.push(path.join(exeDir, "tdk-cli"));
  sources.push(path.join(projectRoot, "..", "tdk-cli"));

  let sourceRoot = "";
  for (const candidate of sources) {
    if (
      candidate &&
      fs.existsSync(path.join(candidate, "Tiltfile")) &&
      fs.existsSync(path.join(candidate, "engine"))
    ) {
      sourceRoot = candidate;
      break;
    }
  }

  if (!sourceRoot) {
    console.warn(
      "⚠️  TDK extension not found - set TDK_EXTENSION_SOURCE to its checkout path " +
        "and re-run `tdk project` (or `tdk config regenerate`) to vendor it before `tdk up`.",
    );
    return;
  }

  if (!fs.existsSync(vendoredDir)) {
    fs.mkdirSync(vendoredDir, { recursive: true });
  }
  fs.copyFileSync(path.join(sourceRoot, "Tiltfile"), path.join(vendoredDir, "Tiltfile"));
  for (const dir of TDK_EXTENSION_DIRS) {
    fs.cpSync(path.join(sourceRoot, dir), path.join(vendoredDir, dir), {
      recursive: true,
    });
  }
  console.log(`✓ Vendored TDK extension → .tdk/.tdk-out/tdk-cli-ext/`);

  // Best-effort: if TDK_LICENSE_KEY is set and grants any paid resource,
  // overlay the premium bundle over the stub files just vendored above.
  // No-ops silently (beyond a warning) if there's no key, the fetch
  // fails, or nothing's granted - the free engine already works fine on
  // its own.
  try {
    const { applyPremiumOverlay } = await import("./extension-fetch.js");
    await applyPremiumOverlay(projectRoot, vendoredDir);
  } catch (err) {
    console.warn(`⚠️  Premium overlay skipped: ${(err as Error).message}`);
  }
}

export function verifyMasterConfigs(projectRoot: string): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  const projectConfig = readProjectConfig(projectRoot);
  const engine = new TemplateEngine();
  const expectedFiles = engine.generateAll(projectConfig);

  const outputDir = path.join(projectRoot, ".tdk", ".tdk-out");

  for (const filename of ALL_GENERATED_FILES) {
    const expectedContent = expectedFiles[filename];
    const filePath = path.join(outputDir, filename);

    if (!fs.existsSync(filePath)) {
      errors.push(`Missing file: .tdk/.tdk-out/${filename}`);
      continue;
    }

    const actualContent = fs.readFileSync(filePath, "utf-8");
    if (actualContent !== expectedContent) {
      errors.push(`Out of sync: .tdk/.tdk-out/${filename} (run 'tdk config regenerate')`);
    }
  }

  return { valid: errors.length === 0, errors };
}
